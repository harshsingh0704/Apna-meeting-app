import React, { useContext, useEffect, useState } from "react";
import { AuthContext } from "../contexts/AuthContext";
import { useNavigate } from "react-router-dom";
import jsPDF from "jspdf";
import server from "../environment";

import Card from "@mui/material/Card";
import CardContent from "@mui/material/CardContent";
import Typography from "@mui/material/Typography";
import HomeIcon from "@mui/icons-material/Home";
import {
  IconButton,
  Divider,
  Chip,
  Box,
  Button,
  TextField,
  Container,
} from "@mui/material";
import DownloadIcon from "@mui/icons-material/Download";

export default function History() {
  const { getHistoryOfUser } = useContext(AuthContext);

  const [meetings, setMeetings] = useState([]);
  const [query, setQuery] = useState("");
  const [analyticsMeetingId, setAnalyticsMeetingId] = useState(null);
  const [analyticsData, setAnalyticsData] = useState(null);
  const [analyticsLoading, setAnalyticsLoading] = useState(false);
  const routeTo = useNavigate();

  const fetchAnalytics = async (meetingId) => {
    if (analyticsMeetingId === meetingId && analyticsData) {
      setAnalyticsMeetingId(null);
      setAnalyticsData(null);
      return;
    }
    setAnalyticsLoading(true);
    setAnalyticsData(null);
    try {
      const token = localStorage.getItem("token");
      const res = await fetch(`${server}/api/v1/meeting/analytics/${meetingId}`, {
        headers: { Authorization: `Bearer ${token}` },
      });
      const data = await res.json();
      if (res.ok) {
        setAnalyticsMeetingId(meetingId);
        setAnalyticsData(data);
      } else {
        console.error("Analytics failed:", data);
      }
    } catch (err) {
      console.error("Analytics error:", err);
    } finally {
      setAnalyticsLoading(false);
    }
  };

  useEffect(() => {
    const fetchHistory = async () => {
      try {
        const history = await getHistoryOfUser();
        setMeetings(history || []);
      } catch (err) {
        console.log("History error:", err);
      }
    };

    fetchHistory();
  }, []);

  const formatDate = (dateString) => {
    const date = new Date(dateString);
    const day = date.getDate().toString().padStart(2, "0");
    const month = (date.getMonth() + 1).toString().padStart(2, "0");
    const year = date.getFullYear();
    return `${day}/${month}/${year}`;
  };

  const handleDownloadPdf = (meeting) => {
    try {
      const doc = new jsPDF({ unit: "pt", format: "a4" });
      const pageW = doc.internal.pageSize.getWidth();
      const pageH = doc.internal.pageSize.getHeight();

      const marginX = 44;
      const headerH = 92;
      const footerH = 34;
      const contentTop = headerH + 18;
      const contentBottom = pageH - footerH;

      const colors = {
        bg: [2, 6, 23], // slate-950-ish
        card: [15, 23, 42], // slate-900
        border: [51, 65, 85], // slate-700
        text: [226, 232, 240], // slate-200
        muted: [148, 163, 184], // slate-400
        accent: [37, 99, 235], // blue-600
      };

      const safe = (v, fallback = "-") =>
        typeof v === "string" && v.trim().length ? v.trim() : fallback;

      const meetingCode = safe(meeting.meetingCode, "-");
      const meetingDate = meeting.date ? formatDate(meeting.date) : "-";

      const summaryText =
        meeting.summary && meeting.summary.trim().length > 0
          ? meeting.summary.trim()
          : "No summary saved.";

      const actionItems =
        Array.isArray(meeting.actionItems) && meeting.actionItems.length > 0
          ? meeting.actionItems.filter(Boolean)
          : [];

      const decisions =
        Array.isArray(meeting.decisions) && meeting.decisions.length > 0
          ? meeting.decisions.filter(Boolean)
          : [];

      const drawHeader = () => {
        // Background band
        doc.setFillColor(...colors.bg);
        doc.rect(0, 0, pageW, headerH, "F");

        // Accent line
        doc.setFillColor(...colors.accent);
        doc.rect(0, headerH - 4, pageW, 4, "F");

        // Title
        doc.setTextColor(...colors.text);
        doc.setFont("helvetica", "bold");
        doc.setFontSize(22);
        doc.text("Meeting Summary", marginX, 48);

        // Meta row
        doc.setFont("helvetica", "normal");
        doc.setFontSize(11);
        doc.setTextColor(...colors.muted);
        doc.text(`Code: ${meetingCode}`, marginX, 72);
        doc.text(`Date: ${meetingDate}`, pageW - marginX, 72, { align: "right" });
      };

      const drawFooter = (pageNo, totalPages) => {
        doc.setDrawColor(...colors.border);
        doc.setLineWidth(1);
        doc.line(marginX, pageH - footerH, pageW - marginX, pageH - footerH);

        doc.setFont("helvetica", "normal");
        doc.setFontSize(10);
        doc.setTextColor(...colors.muted);
        doc.text(
          `Generated by Meeting-AI • ${new Date().toLocaleString()}`,
          marginX,
          pageH - 14
        );
        doc.text(`Page ${pageNo} / ${totalPages}`, pageW - marginX, pageH - 14, {
          align: "right",
        });
      };

      const drawSectionCard = (title, lines, startY) => {
        const cardX = marginX;
        const cardW = pageW - marginX * 2;
        const padding = 14;

        doc.setFont("helvetica", "bold");
        doc.setFontSize(12);
        const titleH = 16;
        const lineH = 14;
        const bodyH = Math.max(lines.length, 1) * lineH;
        const cardH = padding + titleH + 10 + bodyH + padding;

        // Card background
        doc.setFillColor(...colors.card);
        doc.setDrawColor(...colors.border);
        doc.setLineWidth(1);
        doc.roundedRect(cardX, startY, cardW, cardH, 10, 10, "FD");

        // Title
        doc.setTextColor(...colors.text);
        doc.text(title, cardX + padding, startY + padding + titleH - 2);

        // Divider
        doc.setDrawColor(...colors.border);
        doc.setLineWidth(0.8);
        doc.line(
          cardX + padding,
          startY + padding + titleH + 6,
          cardX + cardW - padding,
          startY + padding + titleH + 6
        );

        // Body
        doc.setFont("helvetica", "normal");
        doc.setFontSize(11);
        doc.setTextColor(...colors.muted);
        const bodyStartY = startY + padding + titleH + 18;
        lines.forEach((l, idx) => {
          doc.text(l, cardX + padding, bodyStartY + idx * lineH);
        });

        return startY + cardH + 14; // next cursor
      };

      const addPage = () => {
        doc.addPage();
        drawHeader();
        return contentTop;
      };

      // Page 1
      drawHeader();
      let cursorY = contentTop;

      // Summary card
      doc.setFont("helvetica", "normal");
      doc.setFontSize(11);
      const summaryLines = doc.splitTextToSize(summaryText, 470);

      // If huge summary, we’ll render only what fits on the page and continue on next.
      const renderWrappedInCards = (title, allLines) => {
        let i = 0;
        while (i < allLines.length || allLines.length === 0) {
          const availableH = contentBottom - cursorY;
          // Estimate how many lines can fit in a card.
          const padding = 14;
          const titleH = 16;
          const lineH = 14;
          const maxLines = Math.max(
            1,
            Math.floor((availableH - (padding + titleH + 10 + padding + 14)) / lineH)
          );
          const chunk =
            allLines.length === 0 ? [""] : allLines.slice(i, i + maxLines);

          cursorY = drawSectionCard(title, chunk, cursorY);
          i += chunk.length;

          if (i < allLines.length) cursorY = addPage();
          if (allLines.length === 0) break;
        }
      };

      renderWrappedInCards("Summary", summaryLines);

      // Action items card
      const tasksTextLines =
        actionItems.length > 0
          ? actionItems.flatMap((t) => doc.splitTextToSize(`• ${String(t)}`, 470))
          : ["No tasks saved."];

      renderWrappedInCards("Action Items", tasksTextLines);

      // Decisions card
      const decisionsTextLines =
        decisions.length > 0
          ? decisions.flatMap((d) => doc.splitTextToSize(`• ${String(d)}`, 470))
          : ["No decisions saved."];

      renderWrappedInCards("Decisions", decisionsTextLines);

      // Footer with correct page numbers
      const totalPages = doc.getNumberOfPages();
      for (let p = 1; p <= totalPages; p++) {
        doc.setPage(p);
        drawFooter(p, totalPages);
      }

      const fileName = `meeting-${meetingCode || "summary"}.pdf`;
      doc.save(fileName);
    } catch (err) {
      console.error("PDF export failed:", err);
      alert("Failed to generate PDF. Please try again.");
    }
  };

  const filteredMeetings = meetings
    .slice()
    .sort((a, b) => new Date(b.date || 0) - new Date(a.date || 0))
    .filter((m) => {
      const q = query.trim().toLowerCase();
      if (!q) return true;
      const code = String(m.meetingCode || "").toLowerCase();
      const sum = String(m.summary || "").toLowerCase();
      return code.includes(q) || sum.includes(q);
    });

  return (
    <Box
      sx={{
        minHeight: "100vh",
        background:
          "radial-gradient(circle at 10% 10%, rgba(37,99,235,0.18) 0%, rgba(2,6,23,1) 55%)",
        py: 3,
      }}
    >
      <Container maxWidth="lg">
        {/* Top bar */}
        <Box
          sx={{
            position: "sticky",
            top: 0,
            zIndex: 5,
            backdropFilter: "blur(10px)",
            backgroundColor: "rgba(2,6,23,0.65)",
            border: "1px solid rgba(51,65,85,0.5)",
            borderRadius: 3,
            px: 2,
            py: 1.5,
            mb: 3,
            display: "flex",
            alignItems: "center",
            gap: 1.5,
          }}
        >
          <IconButton
            onClick={() => routeTo("/home")}
            sx={{
              color: "#E2E8F0",
              border: "1px solid rgba(51,65,85,0.8)",
              borderRadius: 2,
            }}
          >
            <HomeIcon />
          </IconButton>

          <Box sx={{ flex: 1 }}>
            <Typography variant="h5" sx={{ fontWeight: 900, color: "white" }}>
              📜 Meeting History
            </Typography>
            <Typography sx={{ color: "#94A3B8", fontSize: 13 }}>
              Search meetings by code or summary • Total:{" "}
              <b style={{ color: "#E2E8F0" }}>{meetings.length}</b>
            </Typography>
          </Box>

          <TextField
            value={query}
            onChange={(e) => setQuery(e.target.value)}
            placeholder="Search… (code / summary)"
            size="small"
            sx={{
              width: { xs: 180, sm: 280, md: 340 },
              "& .MuiInputBase-root": {
                backgroundColor: "rgba(15,23,42,0.7)",
                borderRadius: "12px",
                color: "#E2E8F0",
              },
              "& .MuiOutlinedInput-notchedOutline": {
                borderColor: "rgba(51,65,85,0.8)",
              },
              "&:hover .MuiOutlinedInput-notchedOutline": {
                borderColor: "rgba(96,165,250,0.8)",
              },
              "& .MuiInputBase-input::placeholder": {
                color: "#94A3B8",
                opacity: 1,
              },
            }}
          />
        </Box>

        {filteredMeetings.length !== 0 ? (
          filteredMeetings.map((e, i) => (
            <Card
              key={i}
              variant="outlined"
              sx={{
                mb: 2.5,
                borderRadius: 4,
                background:
                  "linear-gradient(180deg, rgba(15,23,42,0.92), rgba(2,6,23,0.92))",
                color: "white",
                border: "1px solid rgba(51,65,85,0.8)",
                overflow: "hidden",
                transition: "transform 180ms ease, box-shadow 180ms ease",
                "&:hover": {
                  transform: "translateY(-2px)",
                  boxShadow: "0 18px 45px rgba(0,0,0,0.45)",
                  borderColor: "rgba(96,165,250,0.85)",
                },
              }}
            >
              {/* Accent top strip */}
              <Box
                sx={{
                  height: 4,
                  background:
                    "linear-gradient(90deg, rgba(37,99,235,1), rgba(96,165,250,1))",
                }}
              />

              <CardContent sx={{ p: { xs: 2, sm: 2.5 } }}>
                {/* Meta row */}
                <Box
                  sx={{
                    display: "flex",
                    justifyContent: "space-between",
                    alignItems: "flex-start",
                    gap: 2,
                    flexWrap: "wrap",
                    mb: 1.5,
                  }}
                >
                  <Box>
                    <Typography sx={{ fontSize: 13, color: "#94A3B8" }}>
                      🔑 Code
                    </Typography>
                    <Typography sx={{ fontSize: 18, fontWeight: 900 }}>
                      {e.meetingCode || "-"}
                    </Typography>
                  </Box>

                  <Box>
                    <Typography sx={{ fontSize: 13, color: "#94A3B8" }}>
                      📅 Date
                    </Typography>
                    <Typography sx={{ fontSize: 15, fontWeight: 700 }}>
                      {e.date ? formatDate(e.date) : "-"}
                    </Typography>
                  </Box>

                  <Box sx={{ display: "flex", gap: 1, alignItems: "center" }}>
                    <Chip
                      label={
                        e.summary && e.summary.trim().length > 0
                          ? "Summary saved"
                          : "No summary"
                      }
                      size="small"
                      sx={{
                        background:
                          e.summary && e.summary.trim().length > 0
                            ? "rgba(34,197,94,0.15)"
                            : "rgba(239,68,68,0.12)",
                        color:
                          e.summary && e.summary.trim().length > 0
                            ? "#86EFAC"
                            : "#FCA5A5",
                        border: "1px solid rgba(51,65,85,0.6)",
                      }}
                    />
                    <Chip
                      label={
                        Array.isArray(e.actionItems) && e.actionItems.length > 0
                          ? `${e.actionItems.length} tasks`
                          : "0 tasks"
                      }
                      size="small"
                      sx={{
                        background: "rgba(37,99,235,0.14)",
                        color: "#93C5FD",
                        border: "1px solid rgba(51,65,85,0.6)",
                      }}
                    />
                  </Box>
                </Box>

                <Divider sx={{ my: 2, borderColor: "rgba(51,65,85,0.8)" }} />

                {/* Summary */}
                <Typography sx={{ fontSize: 15, fontWeight: 900, mb: 0.75 }}>
                  🧠 Summary
                </Typography>
                <Box
                  sx={{
                    border: "1px solid rgba(51,65,85,0.65)",
                    background: "rgba(2,6,23,0.55)",
                    borderRadius: 3,
                    p: 1.5,
                    mb: 2,
                  }}
                >
                  <Typography
                    sx={{
                      opacity: 0.9,
                      whiteSpace: "pre-line",
                      color: "#E2E8F0",
                      lineHeight: 1.5,
                      fontSize: 14,
                    }}
                  >
                    {e.summary && e.summary.trim().length > 0
                      ? e.summary
                      : "No summary saved yet."}
                  </Typography>
                </Box>

                {/* Tasks */}
                <Typography sx={{ fontSize: 15, fontWeight: 900, mb: 0.75 }}>
                  ✅ Tasks
                </Typography>
                {Array.isArray(e.actionItems) && e.actionItems.length > 0 ? (
                  <Box sx={{ display: "flex", gap: 1, flexWrap: "wrap", mb: 2 }}>
                    {e.actionItems.map((task, idx) => (
                      <Chip
                        key={idx}
                        label={task}
                        sx={{
                          background: "rgba(30,41,59,0.85)",
                          color: "white",
                          border: "1px solid rgba(51,65,85,0.8)",
                        }}
                      />
                    ))}
                  </Box>
                ) : (
                  <Typography sx={{ opacity: 0.75, mb: 2, color: "#CBD5E1" }}>
                    No tasks saved yet.
                  </Typography>
                )}

                {/* Decisions */}
                <Typography sx={{ fontSize: 15, fontWeight: 900, mb: 0.75 }}>
                  📌 Decisions
                </Typography>
                {Array.isArray(e.decisions) && e.decisions.length > 0 ? (
                  <Box sx={{ display: "flex", flexDirection: "column", gap: 0.75, mb: 2 }}>
                    {e.decisions.map((dec, idx) => (
                      <Typography
                        key={idx}
                        sx={{
                          background: "rgba(30,41,59,0.85)",
                          color: "#E2E8F0",
                          border: "1px solid rgba(51,65,85,0.8)",
                          borderRadius: 2,
                          p: 1.25,
                          fontSize: 14,
                        }}
                      >
                        • {dec}
                      </Typography>
                    ))}
                  </Box>
                ) : (
                  <Typography sx={{ opacity: 0.75, mb: 2, color: "#CBD5E1" }}>
                    No decisions saved yet.
                  </Typography>
                )}

                {/* Recording */}
                <Typography sx={{ fontSize: 15, fontWeight: 900, mb: 0.75 }}>
                  🎥 Recording
                </Typography>
                {e.recordingUrl && e.recordingUrl.trim().length > 0 ? (
                  <Box sx={{ mt: 1 }}>
                    <Typography sx={{ opacity: 0.85, mb: 1, color: "#CBD5E1" }}>
                      Duration:{" "}
                      <b style={{ color: "#E2E8F0" }}>
                        {e.recordingDuration
                          ? `${Math.floor(e.recordingDuration / 60)}:${String(
                              e.recordingDuration % 60
                            ).padStart(2, "0")}`
                          : "Unknown"}
                      </b>
                    </Typography>
                    <video
                      controls
                      src={e.recordingUrl}
                      style={{
                        width: "100%",
                        maxHeight: 320,
                        borderRadius: 12,
                        border: "1px solid rgba(51,65,85,0.8)",
                        background: "black",
                      }}
                    />
                  </Box>
                ) : (
                  <Typography sx={{ opacity: 0.75, color: "#CBD5E1" }}>
                    No recording saved for this meeting.
                  </Typography>
                )}

                {/* Advanced Analytics Dashboard */}
                <Typography sx={{ fontSize: 15, fontWeight: 900, mb: 0.75, mt: 2 }}>
                  📊 Advanced Analytics
                </Typography>
                <Button
                  size="small"
                  variant="outlined"
                  onClick={() => fetchAnalytics(e._id)}
                  disabled={analyticsLoading}
                  sx={{
                    mb: 2,
                    color: "#93C5FD",
                    borderColor: "rgba(51,65,85,0.8)",
                    "&:hover": { borderColor: "#60A5FA", bgcolor: "rgba(37,99,235,0.08)" },
                  }}
                >
                  {analyticsMeetingId === e._id ? "Hide Analytics" : "View Analytics"}
                </Button>

                {analyticsMeetingId === e._id && analyticsData && (
                  <Box
                    sx={{
                      border: "1px solid rgba(51,65,85,0.8)",
                      borderRadius: 3,
                      p: 2,
                      mb: 2,
                      background: "rgba(2,6,23,0.6)",
                    }}
                  >
                    {/* Speaker-wise metrics */}
                    <Typography sx={{ fontSize: 14, fontWeight: 800, mb: 1, color: "#93C5FD" }}>
                      👤 Speaker-wise metrics
                    </Typography>
                    {analyticsData.speakerMetrics?.length > 0 ? (
                      <Box sx={{ mb: 2 }}>
                        <Box
                          sx={{
                            display: "grid",
                            gridTemplateColumns: "1fr auto auto",
                            gap: 1,
                            fontSize: 13,
                            color: "#94A3B8",
                            mb: 0.5,
                            px: 1,
                          }}
                        >
                          <span>Speaker</span>
                          <span>Messages</span>
                          <span>Words</span>
                        </Box>
                        {analyticsData.speakerMetrics.map((s, i) => (
                          <Box
                            key={i}
                            sx={{
                              display: "grid",
                              gridTemplateColumns: "1fr auto auto",
                              gap: 1,
                              py: 0.75,
                              px: 1,
                              borderRadius: 1,
                              bgcolor: "rgba(30,41,59,0.5)",
                              mb: 0.5,
                              color: "#E2E8F0",
                              fontSize: 14,
                            }}
                          >
                            <span>{s.name}</span>
                            <span>{s.messageCount}</span>
                            <span>{s.wordCount}</span>
                          </Box>
                        ))}
                      </Box>
                    ) : (
                      <Typography sx={{ fontSize: 13, color: "#94A3B8", mb: 2 }}>
                        No speaker data (meeting context empty).
                      </Typography>
                    )}

                    {/* Engagement graph */}
                    <Typography sx={{ fontSize: 14, fontWeight: 800, mb: 1, color: "#93C5FD" }}>
                      📈 Engagement (messages by phase)
                    </Typography>
                    {analyticsData.engagementBuckets?.length > 0 ? (
                      <Box sx={{ mb: 2 }}>
                        {analyticsData.engagementBuckets.map((b, i) => {
                          const max = Math.max(
                            ...analyticsData.engagementBuckets.map((x) => x.count),
                            1
                          );
                          const pct = max ? (b.count / max) * 100 : 0;
                          return (
                            <Box key={i} sx={{ mb: 1 }}>
                              <Box
                                sx={{
                                  display: "flex",
                                  justifyContent: "space-between",
                                  fontSize: 12,
                                  color: "#94A3B8",
                                  mb: 0.25,
                                }}
                              >
                                <span>{b.label}</span>
                                <span>{b.count} msgs</span>
                              </Box>
                              <Box
                                sx={{
                                  height: 20,
                                  borderRadius: 2,
                                  bgcolor: "rgba(51,65,85,0.5)",
                                  overflow: "hidden",
                                }}
                              >
                                <Box
                                  sx={{
                                    width: `${pct}%`,
                                    height: "100%",
                                    bgcolor: "rgba(37,99,235,0.8)",
                                    borderRadius: 2,
                                    transition: "width 0.3s ease",
                                  }}
                                />
                              </Box>
                            </Box>
                          );
                        })}
                      </Box>
                    ) : (
                      <Typography sx={{ fontSize: 13, color: "#94A3B8", mb: 2 }}>
                        No engagement data.
                      </Typography>
                    )}

                    {/* Keyword trends */}
                    <Typography sx={{ fontSize: 14, fontWeight: 800, mb: 1, color: "#93C5FD" }}>
                      🔑 Keyword trends
                    </Typography>
                    {analyticsData.keywordTrends?.length > 0 ? (
                      <Box sx={{ display: "flex", flexWrap: "wrap", gap: 1 }}>
                        {analyticsData.keywordTrends.map((k, i) => (
                          <Chip
                            key={i}
                            label={`${k.word} (${k.count})`}
                            size="small"
                            sx={{
                              background: "rgba(37,99,235,0.15)",
                              color: "#93C5FD",
                              border: "1px solid rgba(51,65,85,0.6)",
                            }}
                          />
                        ))}
                      </Box>
                    ) : (
                      <Typography sx={{ fontSize: 13, color: "#94A3B8" }}>
                        No keywords (meeting context empty).
                      </Typography>
                    )}
                  </Box>
                )}

                {/* Actions */}
                <Box
                  sx={{
                    mt: 3,
                    display: "flex",
                    justifyContent: "flex-end",
                    gap: 1,
                  }}
                >
                  <Button
                    variant="contained"
                    startIcon={<DownloadIcon />}
                    onClick={() => handleDownloadPdf(e)}
                    sx={{
                      borderRadius: 2.5,
                      fontWeight: 900,
                      textTransform: "none",
                      background:
                        "linear-gradient(90deg, rgba(37,99,235,1), rgba(96,165,250,1))",
                      boxShadow: "0 10px 20px rgba(37,99,235,0.25)",
                      "&:hover": {
                        boxShadow: "0 14px 30px rgba(37,99,235,0.35)",
                      },
                    }}
                  >
                    Download PDF
                  </Button>
                </Box>
              </CardContent>
            </Card>
          ))
        ) : (
          <Box
            sx={{
              mt: 8,
              textAlign: "center",
              border: "1px solid rgba(51,65,85,0.7)",
              background: "rgba(2,6,23,0.6)",
              borderRadius: 4,
              p: 4,
            }}
          >
            <Typography sx={{ fontSize: 22, fontWeight: 900, color: "white" }}>
              No meetings found
            </Typography>
            <Typography sx={{ mt: 1, color: "#94A3B8" }}>
              Try clearing the search, or create a new meeting to see it here.
            </Typography>
          </Box>
        )}
      </Container>
    </Box>
  );
}
